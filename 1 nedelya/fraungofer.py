import numpy as np
import matplotlib.pyplot as plt

# ==========================================
# 1. ФИЗИЧЕСКИЕ ПАРАМЕТРЫ
# ==========================================
wavelength = 0.5e-6    # Длина волны: 500 нм (зеленый свет)
k = 2 * np.pi / wavelength # Волновое число
z = 0.05               # Расстояние до экрана: 5 см

# Геометрия преграды (1 щель)
d = 0.00005            # Ширина щели: 0.05 мм (50 мкм)
slit_height = 0.001    # Высота щели: 1 мм

# --- ТЕОРЕТИЧЕСКИЕ РАСЧЕТЫ ---
S_diff = (wavelength * z) / d  # Расстояние от максимума до первого нуля
print(f"--- Теоретические расчеты ---")
print(f"Ширина щели (d): {d*1000} мм")
print(f"Первый ноль дифракции Фраунгофера (S_diff): {S_diff*1000} мм")
print(f"Полная ширина центрального пятна (2 * S_diff): {2 * S_diff * 1000} мм")
print(f"-----------------------------")

# Параметры сетки
L = 0.002              # Физический размер моделируемой области: 2 мм
N = int(L**2 / (wavelength * z) * 6)              # Разрешение сетки: 800x800 пикселей
dx = L / N  # Физический размер одного пикселя
print(f"Запуск симуляции (Сетка {N}x{N})...")

# ==========================================
# 2. ПОДГОТОВКА ПРОСТРАНСТВА И ПРЕГРАДЫ
# ==========================================
# Создаем координаты для физической сетки
x = np.arange(-N//2, N//2) * dx
y = np.arange(-N//2, N//2) * dx
X, Y = np.meshgrid(x, y)

# Матрица преграды (1 = свет проходит, 0 = блокируется)
E_out = np.zeros((N, N))
# Пример щелей шириной 0.05 мм и высотой 1 мм, разнесенных на 0.2 мм
E_out[(np.abs(Y) < slit_height/2) & (np.abs(X) < d/2)] = 1.0

# ==========================================
# 3. ЗАЩИТА ОТ АРТЕФАКТОВ (Zero-Padding)
# ==========================================
# Расширяем матрицу преграды нулями до размера 2N x 2N
E_padded = np.pad(E_out, pad_width=N//2, mode='constant', constant_values=0)

# Создаем расширенную сетку координат для импульсного отклика (2N x 2N)
x_pad = np.arange(-N, N) * dx
y_pad = np.arange(-N, N) * dx
X_pad, Y_pad = np.meshgrid(x_pad, y_pad)

# ==========================================
# 4. ИМПУЛЬСНЫЙ ОТКЛИК И ФУРЬЕ-СВЕРТКА
# ==========================================
# Считаем точное расстояние r от начала координат до каждой точки сетки
r = np.sqrt(X_pad**2 + Y_pad**2 + z**2)

# Функция импульсного отклика свободного пространства (h)
h = np.exp(-1j * k * r) / r

# Тот самый магический сдвиг центра координат для алгоритма FFT
h_shifted = np.fft.ifftshift(h)

# Переходим в частотную область (БПФ)
H_freq = np.fft.fft2(h_shifted)
E_freq = np.fft.fft2(E_padded)

# Свертка (Умножаем матрицы и делаем обратное БПФ)
E_screen_padded = np.fft.ifft2(E_freq * H_freq)

# ==========================================
# 5. ВОЗВРАТ К РЕАЛЬНОСТИ И ОТРИСОВКА
# ==========================================
# Обрезаем лишние края (возвращаемся к оригинальному размеру N x N)
E_screen = E_screen_padded[N//2 : N//2 + N, N//2 : N//2 + N]

# Интенсивность (квадрат модуля комплексного поля)
I = np.abs(E_screen)**2

# --- Подготовка 1D Графика ---
# Берем центральный срез по горизонтали
I_sim_1d = I[N//2, :]
I_sim_1d = I_sim_1d / np.max(I_sim_1d) # Нормируем к 1

# Считаем теорию для этих же X координат (np.sinc в numpy уже включает pi)
I_theory_1d = np.sinc((d * x) / (wavelength * z))**2

# --- Визуализация (3 панели) ---
plt.figure(figsize=(15, 5))

# 1. Преграда
plt.subplot(1, 3, 1)
plt.title("Преграда (Транспарант)")
plt.imshow(E_out, extent=(-L/2*1000, L/2*1000, -L/2*1000, L/2*1000), cmap='gray')
plt.xlabel("мм")
plt.ylabel("мм")

# 2. Экран 2D
plt.subplot(1, 3, 2)
plt.title(f"Экран на расстоянии z = {z*100} см")
plt.imshow(I**0.4, extent=(-L/2*1000, L/2*1000, -L/2*1000, L/2*1000), cmap='hot')
plt.xlabel("мм")

# 3. График 1D
plt.subplot(1, 3, 3)
plt.title("1D Срез интенсивности vs Теория")
plt.plot(x * 1000, I_sim_1d, label='Симуляция (Срез матрицы)', color='blue', linewidth=3)
plt.plot(x * 1000, I_theory_1d, label='Теория (sinc²)', color='red', linestyle='--', linewidth=2)

# Отмечаем расчетные нули S_diff на графике
plt.axvline(x=S_diff*1000, color='green', linestyle=':', label=f'Расчетный S_diff ({S_diff*1000} мм)')
plt.axvline(x=-S_diff*1000, color='green', linestyle=':')

plt.xlabel("Координата X (мм)")
plt.ylabel("Интенсивность (норм.)")
plt.legend(loc='upper right', fontsize=8)
plt.grid(True, alpha=0.3)
plt.xlim(-L/2*1000, L/2*1000)

plt.tight_layout()
plt.show()
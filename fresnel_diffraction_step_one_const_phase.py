import numpy as np
import matplotlib.pyplot as plt

# ==========================================
# 1. ФИЗИЧЕСКИЕ ПАРАМЕТРЫ
# ==========================================
wavelength = 0.5e-6    # Длина волны: 500 нм (зеленый свет)
k = 2 * np.pi / wavelength # Волновое число
z = 0.05               # Расстояние до экрана: 5 см
R = 0.0002             # Радиус отверстия: 0.2 мм

# Параметры сетки
L = 0.002              # Физический размер моделируемой области: 2 мм
N = int(L**2 / (wavelength * z) * 6)              # Разрешение сетки: 800x800 пикселей

print(f"Запуск симуляции (Сетка {N}x{N})...")

# ==========================================
# 2. ПОДГОТОВКА ПРОСТРАНСТВА И ПРЕГРАДЫ
# ==========================================
# Создаем координаты для физической сетки
x = np.linspace(-L/2, L/2, N)
y = np.linspace(-L/2, L/2, N)
X, Y = np.meshgrid(x, y)

# Матрица преграды (1 = свет проходит, 0 = блокируется)
E_out = np.zeros((N, N))
# Пример щелей шириной 0.05 мм и высотой 1 мм, разнесенных на 0.2 мм
E_out[X**2 + Y**2 <= R**2] = 1.0

# ==========================================
# 3. ЗАЩИТА ОТ АРТЕФАКТОВ (Zero-Padding)
# ==========================================
# Расширяем матрицу преграды нулями до размера 2N x 2N
E_padded = np.pad(E_out, pad_width=N//2, mode='constant', constant_values=0)

# Создаем расширенную сетку координат для импульсного отклика (2N x 2N)
L_pad = L * 2
x_pad = np.linspace(-L_pad/2, L_pad/2, 2*N)
y_pad = np.linspace(-L_pad/2, L_pad/2, 2*N)
X_pad, Y_pad = np.meshgrid(x_pad, y_pad)

# ==========================================
# 4. ИМПУЛЬСНЫЙ ОТКЛИК И ФУРЬЕ-СВЕРТКА
# ==========================================
# Считаем точное расстояние r от начала координат до каждой точки сетки
r = np.sqrt(X_pad**2 + Y_pad**2 + z**2)

# Функция импульсного отклика свободного пространства (h)
h = np.exp(-1j * k * r) / r

# Тот самый магический сдвиг центра координат для алгоритма FFT
h_shifted = np.fft.ifftshift(h)

# Переходим в частотную область (БПФ)
H_freq = np.fft.fft2(h_shifted)
E_freq = np.fft.fft2(E_padded)

# Свертка (Умножаем матрицы и делаем обратное БПФ)
E_screen_padded = np.fft.ifft2(E_freq * H_freq)

# ==========================================
# 5. ВОЗВРАТ К РЕАЛЬНОСТИ И ОТРИСОВКА
# ==========================================
# Обрезаем лишние края (возвращаемся к оригинальному размеру N x N)
E_screen = E_screen_padded[N//2 : N//2 + N, N//2 : N//2 + N]

# Интенсивность (квадрат модуля комплексного поля)
I = np.abs(E_screen)**2

# --- Визуализация ---
plt.figure(figsize=(10, 5))

# Отрисовка преграды
plt.subplot(1, 2, 1)
plt.title("Преграда (Транспарант)")
plt.imshow(E_out, extent=(-L/2*1000, L/2*1000, -L/2*1000, L/2*1000), cmap='gray')
plt.xlabel("мм")
plt.ylabel("мм")

# Отрисовка экрана (используем степень 0.4 для гамма-коррекции,
# чтобы слабые вторичные кольца было видно на фоне яркого центра)
plt.subplot(1, 2, 2)
plt.title(f"Экран на расстоянии z = {z*100} см")
plt.imshow(I**0.4, extent=(-L/2*1000, L/2*1000, -L/2*1000, L/2*1000), cmap='hot')
plt.xlabel("мм")

plt.tight_layout()
plt.show()